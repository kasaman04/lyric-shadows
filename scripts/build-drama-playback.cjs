// Build one seekable track per episode, with sample-accurate card boundaries.
// Run again after adding or changing drama clips. Requires ffmpeg on PATH.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'public/dramas.js'), 'utf8'), context);
const tracks = {};
function ffmpeg(args, maxBuffer = 64 * 1024 * 1024) {
  const result = spawnSync('ffmpeg', ['-nostdin', '-v', 'error', ...args], { maxBuffer });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr.toString());
  return result.stdout;
}
for (const drama of context.window.DRAMAS) {
  for (const episode of drama.episodes) {
    const relative = `/drama-audio/${drama.id}/${episode.id}/continuous-20261009-v1.mp3`;
    const output = path.join(root, 'public', relative);
    const pcmPath = `${output}.pcm`;
    const temporary = `${output}.tmp.mp3`;
    const starts = [];
    let samples = 0;
    const fd = fs.openSync(pcmPath, 'w');
    try {
      for (const clip of episode.clips) {
        const source = path.resolve(root, 'public', `.${clip.audio}`);
        const pcm = ffmpeg(['-i', source, '-ar', '44100', '-ac', '1', '-f', 's16le', 'pipe:1']);
        if (!pcm.length || pcm.length % 2) throw new Error(`Invalid decoded clip: ${source}`);
        starts.push(Number((samples / 44100).toFixed(6)));
        fs.writeFileSync(fd, pcm);
        samples += pcm.length / 2;
      }
    } finally {
      fs.closeSync(fd);
    }
    try {
      ffmpeg(['-y', '-f', 's16le', '-ar', '44100', '-ac', '1', '-i', pcmPath,
        '-c:a', 'libmp3lame', '-b:a', '128k', '-write_xing', '1', temporary]);
      const decoded = ffmpeg(['-i', temporary, '-ar', '44100', '-ac', '1', '-f', 's16le', 'pipe:1']);
      if (decoded.length / 2 !== samples) throw new Error(`Combined track lost samples: ${episode.id}`);
      fs.renameSync(temporary, output);
      tracks[`${drama.id}:${episode.id}`] = { audio: relative, duration: samples / 44100, starts };
      console.log(`${drama.id}/${episode.id}: ${starts.length} clips, ${(samples / 44100).toFixed(2)} seconds`);
    } finally {
      fs.unlinkSync(pcmPath);
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    }
  }
}
fs.writeFileSync(path.join(root, 'public/drama-playback.js'),
  `// Generated by scripts/build-drama-playback.cjs; times are decoded sample boundaries.\nwindow.DRAMA_PLAYBACK = ${JSON.stringify(tracks, null, 2)};\n`);
