'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {VOICE_PROFILES}=require('../lib/voice-catalog');
const {TTS_MODEL_ID}=require('../lib/elevenlabs-model');
const root=path.resolve(__dirname,'..');
const outputDir=path.resolve(root,'../output/conversation-connectors-20261105');
const keys=['by the time','whether','now that','once','so that','in case','as soon as','even though','unless','while','as'];
const basic=new Set(['once','as soon as','even though','unless','while','as']);
const counts=new Map();
const rows=fs.readFileSync(path.join(root,'data/conversation-connectors-additions.tsv'),'utf8').trim().split(/\r?\n/).slice(1);
const conversations=rows.map(row=>{
 const cells=row.split('\t');assert.equal(cells.length,9,row);
 const [type,title,target,aEn,aJa,bEn,bJa,a2En,a2Ja]=cells;
 assert(keys.includes(type),type);const number=(counts.get(type)||0)+1;counts.set(type,number);
 const turns=[{speaker:'A',en:aEn,ja:aJa},{speaker:'B',en:bEn,ja:bJa},{speaker:'A',en:a2En,ja:a2Ja}];
 const targetTurnIndex=Number(target);assert([0,1,2].includes(targetTurnIndex));
 const targetSentence=turns[targetTurnIndex].en;assert(new RegExp('\\b'+type+'\\b','i').test(targetSentence));
 return {id:type.replaceAll(' ','-')+'-dialogue-'+String(number).padStart(2,'0'),type,title,targetTurnIndex,targetSentence,turns};
});
assert.equal(conversations.length,110);for(const key of keys)assert.equal(counts.get(key),10,key);
assert.equal(new Set(conversations.flatMap(c=>c.turns.map(t=>t.en))).size,330,'Keep the new conversation turns distinct');
const pack={title:'日常会話をつなぐ11表現・3ターン会話110',createdDate:'2026-11-05',description:'各表現10会話。A/Bの3ターンと日本語訳。',conversations};
fs.writeFileSync(path.join(root,'data/conversation-connectors-additions.json'),JSON.stringify(pack,null,2)+'\n');
fs.mkdirSync(outputDir,{recursive:true});
const review=conversations.map(c=>'## '+c.type+' / '+c.title+'\n\n'+c.turns.map(t=>t.speaker+': '+t.en+'\n'+t.ja).join('\n\n')).join('\n\n');
fs.writeFileSync(path.join(outputDir,'conversation-review.md'),'# 追加する会話フレーズ110件\n\n'+review+'\n');
if(process.argv.includes('--apply')){
 const manifest=JSON.parse(fs.readFileSync(path.join(outputDir,'audio/manifest.json'),'utf8'));
 assert.equal(manifest.provider,'elevenlabs');assert.equal(manifest.model,TTS_MODEL_ID);
 const cast=['mark','belle'].map(key=>VOICE_PROFILES.find(v=>v.key===key));
 const missing=conversations.filter(c=>!manifest.conversations[c.id]);
 if(!process.argv.includes('--allow-partial'))assert.equal(missing.length,0,'Audio is incomplete; use --allow-partial only to prepare an explicitly partial release');
 const added=conversations.filter(c=>manifest.conversations[c.id]).map(c=>{
  const audio=manifest.conversations[c.id];assert(audio,c.id+' audio missing');
  const hash=crypto.createHash('sha256').update(JSON.stringify({turns:c.turns.map(t=>t.en),cast:cast.map(v=>v.id),model:TTS_MODEL_ID,format:'pcm24000-to-mp3-96k-v1'})).digest('hex');
  assert.equal(audio.sourceHash,hash,c.id+' stale audio');
  const source=path.resolve(outputDir,audio.src);assert(source.startsWith(outputDir+path.sep));assert(fs.statSync(source).size>1000,c.id);
  const filename=path.basename(source),relative='/relative-phrase-audio/'+filename;
  fs.mkdirSync(path.join(root,'public/relative-phrase-audio'),{recursive:true});
  fs.copyFileSync(source,path.join(root,'public',relative));
  return {id:c.id,pack:basic.has(c.type)?'基本':'応用',category:c.type,relativeType:c.type,targetLineIndex:c.targetTurnIndex,phrase:c.targetSentence,usageNote:c.title,audio:relative,audioDuration:audio.duration,audioCues:audio.cues,voiceCast:audio.voices,lines:c.turns.map(t=>[t.speaker,t.en,t.ja])};
 });
 const file=path.join(root,'data/relative-conversation-phrases.json');
 const existing=JSON.parse(fs.readFileSync(file,'utf8')).filter(p=>!keys.includes(p.category));
 assert.equal(existing.length,150);const combined=[...existing,...added];assert.equal(new Set(combined.map(p=>p.id)).size,150+added.length);
 fs.writeFileSync(file,JSON.stringify(combined,null,2)+'\n');
 fs.copyFileSync(path.join(outputDir,'audio/manifest.json'),path.join(root,'data/conversation-connectors-audio.json'));
 console.log(JSON.stringify({applied:true,added:added.length,total:combined.length,categories:new Set(combined.map(p=>p.category)).size,pendingAudio:missing.map(c=>c.id)}));
}else console.log(JSON.stringify({prepared:true,conversations:conversations.length,categories:keys.length,review:path.join(outputDir,'conversation-review.md')}));
