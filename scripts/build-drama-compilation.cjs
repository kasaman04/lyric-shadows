// Join the existing episode tracks without changing any episode or source clip.
// Usage: node scripts/build-drama-compilation.cjs first-love-2022
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const context = { window: {} };
for (const file of ['dramas.js', 'drama-playback.js']) {
  vm.runInNewContext(fs.readFileSync(path.join(root, 'public', file), 'utf8'), context);
}
const dramaId = process.argv[2] || 'first-love-2022';
const drama = context.window.DRAMAS.find(item => item.id === dramaId);
if (!drama) throw new Error(`Unknown drama: ${dramaId}`);
const episodes = [...drama.episodes].sort((a, b) => a.number - b.number);
const output = path.join(root, 'public/drama-audio', dramaId, 'all-episodes-20261029-v1.mp3');
if (fs.existsSync(output)) throw new Error(`Refusing to overwrite: ${output}`);
const pcmPath = `${output}.pcm`;
const temporary = `${output}.tmp.mp3`;
function ffmpeg(args) {
  const result = spawnSync('ffmpeg', ['-nostdin', '-v', 'error', ...args], { maxBuffer: 256 * 1024 * 1024 });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr.toString());
  return result.stdout;
}
let samples = 0;
const starts = [], episodeStarts = [];
const fd = fs.openSync(pcmPath, 'wx');
try {
  for (const episode of episodes) {
    const track = context.window.DRAMA_PLAYBACK[`${dramaId}:${episode.id}`];
    if (!track || track.starts.length !== episode.clips.length) throw new Error(`Missing episode track: ${episode.id}`);
    const pcm = ffmpeg(['-i', path.join(root, 'public', track.audio), '-ar', '44100', '-ac', '1', '-f', 's16le', 'pipe:1']);
    const expectedSamples = Math.round(track.duration * 44100);
    if (pcm.length !== expectedSamples * 2) throw new Error(`Episode duration mismatch: ${episode.id}`);
    episodeStarts.push({ id: episode.id, clipIndex: starts.length, start: samples / 44100 });
    starts.push(...track.starts.map(start => Number(((samples + Math.round(start * 44100)) / 44100).toFixed(6))));
    fs.writeFileSync(fd, pcm);
    samples += expectedSamples;
  }
} finally {
  fs.closeSync(fd);
}
try {
  ffmpeg(['-n', '-f', 's16le', '-ar', '44100', '-ac', '1', '-i', pcmPath,
    '-c:a', 'libmp3lame', '-b:a', '128k', '-write_xing', '1',
    '-metadata', `title=${drama.title} 全話まとめ`, temporary]);
  const decoded = ffmpeg(['-i', temporary, '-ar', '44100', '-ac', '1', '-f', 's16le', 'pipe:1']);
  if (decoded.length !== samples * 2) throw new Error('Combined track lost samples');
  fs.renameSync(temporary, output);
  const entry = {
    id: 'all-episodes', title: '全話まとめ',
    episodeIds: episodes.map(episode => episode.id), episodeStarts,
    audio: `/drama-audio/${dramaId}/${path.basename(output)}`, duration: samples / 44100, starts,
  };
  const compilationsFile = path.join(root, 'public/drama-compilations.js');
  const previous = { window: { DRAMA_PLAYBACK: {} } };
  if (fs.existsSync(compilationsFile)) vm.runInNewContext(fs.readFileSync(compilationsFile, 'utf8'), previous);
  const compilations = { ...previous.window.DRAMA_COMPILATIONS, [dramaId]: entry };
  fs.writeFileSync(compilationsFile,
    '// Generated by scripts/build-drama-compilation.cjs. Original episodes remain unchanged.\n' +
    `window.DRAMA_COMPILATIONS = ${JSON.stringify(compilations, null, 2)};\n` +
    'for (const [dramaId, track] of Object.entries(window.DRAMA_COMPILATIONS)) {\n' +
    '  window.DRAMA_PLAYBACK[`${dramaId}:${track.id}`] = track;\n}\n');
  console.log(JSON.stringify({ dramaId, episodes: episodes.length, clips: starts.length, duration: entry.duration, output }));
} finally {
  if (fs.existsSync(pcmPath)) fs.unlinkSync(pcmPath);
  if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
}
